export type Dict = (typeof dict)["en"];

type Ctx = { lang: Lang; dir: "ltr" | "rtl"; t: Dict; setLang: (l: Lang) => void; locale: string };
const I18nContext = createContext<Ctx | null>(null);

function readInitial(): Lang {
  const stored = typeof localStorage !== "undefined" ? localStorage.getItem(STORAGE_KEY) : null;
  return stored === "ar" ? "ar" : "en";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readInitial);

  useEffect(() => {
    const dir = lang === "ar" ? "rtl" : "ltr";
    document.documentElement.setAttribute("lang", lang);
    document.documentElement.setAttribute("dir", dir);
    localStorage.setItem(STORAGE_KEY, lang);
    // Warm every Tajawal weight the moment Arabic is active: the faces are
    // font-display:swap, so without this a fresh load paints the client
    // document (cover included) in the system Arabic font until the files
    // arrive. Preloading turns that flash into a non-event.
    if (lang === "ar" && "fonts" in document) {
      for (const w of ["400", "500", "700"]) void document.fonts.load(`${w} 16px Tajawal`, "نص عربي");
    }
  }, [lang]);

  const value = useMemo<Ctx>(
    () => ({
      lang,
      dir: lang === "ar" ? "rtl" : "ltr",
      t: dict[lang] as unknown as Dict,
      setLang: setLangState,
      // Western Arabic numerals in both languages per HNI rule; locale still drives separators.
      locale: lang === "ar" ? "ar-SA-u-nu-latn" : "en-US",
    }),
    [lang],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}

/** The pricing dictionary for an explicit language, independent of the UI language (per-export language, eng review T4). */
export function getPricingDict(lang: Lang): Dict["pricing"] {
  return dict[lang].pricing as unknown as Dict["pricing"];
}

export function formatCurrency(value: number, locale: string) {
  const n = new Intl.NumberFormat(locale, { maximumFractionDigits: 0 }).format(Math.abs(value));
  const unit = locale.startsWith("ar") ? "ر.س" : "SAR";
  return `${value < 0 ? "−" : ""}${unit} ${n}`;
}
